def _apply(rows: dict) -> None:
    bind = op.get_bind()
    for rule_code, row in rows.items():
        bind.execute(
            _APPLY,
            {
                "rule_code": rule_code,
                "check_point": row["check_point"],
                "llm_checks": json.dumps(row["llm_checks"], ensure_ascii=False),
            },
        )


